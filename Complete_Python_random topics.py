def print_question_counts():
    """Print the number of questions in each topic."""
    total = 0
    for topic, questions in QUESTION_BANK.items():
        print(f"{topic}: {len(questions)} questions")
        total += len(questions)
    print(f"\nTotal: {total} questions across {len(QUESTION_BANK)} topics")


def print_topic(topic_number=None):
    """Print all questions, or the questions for one numbered topic."""
    topics = list(QUESTION_BANK.items())
    if topic_number is None:
        for index, (topic, questions) in enumerate(topics, start=1):
            print(f"\n{index}. {topic}")
            for number, question in enumerate(questions, start=1):
                print(f"   {number}. {question}")
        return

    if not isinstance(topic_number, int) or not 1 <= topic_number <= len(topics):
        print(f"Enter a topic number from 1 to {len(topics)}.")
        return
    topic, questions = topics[topic_number - 1]
    print(f"\n{topic}")
    for number, question in enumerate(questions, start=1):
        print(f"{number}. {question}")


